"""The forty shipped IPC-2026 rainbowttles instances, written down as data.

The "ipc" variant rebuilds these instead of drawing its own puzzle, so its only
instance parameter is the index below, which is the number in the file name:
p11-p30 are the opt track and p31-p50 the sat track. Both tracks ship the same
domain, so one table covers them.

Each entry holds everything needed to rebuild that instance:

- ``capacity``   how many segments every bottle of the puzzle holds (4 in all
                 forty, kept per instance anyway so the table stands alone);
- ``n_colours``  how many playable colours it uses. They are always the first
                 n of ``COLOUR_PALETTE``, in that order, plus the empty marker;
- ``stacks``     one entry per bottle, in the order the instance names them
                 (bottle01 first). A stack lists the bottle's contents **bottom
                 first** as ``(colour index, run length)`` pairs, so ``[(1, 2),
                 (0, 1)]`` is a bottle holding two segments of colour 1 with one
                 segment of colour 0 resting on top. An empty bottle is ``[]``.

A colour never appears twice in one stack: the domain keeps a single
``colour-segments`` count per bottle and colour, so a state that split a colour
into two runs in one bottle could not be written down at all. Every stack here
was checked against the ``upper-colour`` and ``colour-below`` chains of the file
it came from, so the three encodings agree.

This is transcribed from the shipped instances, not generated by a scramble, and
the original generator is not available - so there is no seed here and no
witness plan for these instances, only the puzzle itself.
"""

